namespace BrainstormBuddy.Memory.Extraction;

/// <summary>
/// Versioned system-prompts для memory extraction (спека: PROMPTS хранятся
/// как versioned resources — bump <see cref="PromptVersion"/> при изменении
/// схемы/инструкций, чтобы можно было мигрировать старые результаты).
/// </summary>
public static class MemoryPrompts
{
    /// <summary>Версия промпта/JSON-схемы. Сохранять в metadata job/result.
    /// v2 (аудит 2026-10-15, §6.4): добавлена клауза интенсивности извлечения.</summary>
    public const int PromptVersion = 2;

    /// <summary>
    /// Извлечение: краткое саммари встречи + массив memories по строгой JSON-схеме.
    /// Фильтрация «мусора» (привет/спасибо/слышно) — на стороне LLM через этот
    /// system-prompt: extractor отдаёт транскрипт ЦЕЛИКОМ, без локальной фильтрации.
    /// </summary>
    public const string Extract =
        "Ты — модуль памяти ассистента. По транскрипту встречи извлеки краткое саммари " +
        "и долговременные факты (memories). Ответь ТОЛЬКО валидным JSON по схеме ниже — " +
        "без markdown, без пояснений, без обрамления в ```.\n\n" +
        "СХЕМА ОТВЕТА:\n" +
        "{\n" +
        "  \"summary\": \"краткое саммари встречи, 2-4 предложения, по-русски\",\n" +
        "  \"memories\": [\n" +
        "    {\n" +
        "      \"type\": \"decision|action_item|deadline|open_question|risk|idea|preference|" +
        "constraint|correction|person|project|fact\",\n" +
        "      \"content\": \"одно конкретное утверждение\",\n" +
        "      \"importance\": 0.0-1.0,\n" +
        "      \"confidence\": 0.0-1.0,\n" +
        "      \"speakerId\": \"S1 (если понятно, кто сказал/принял, иначе null)\",\n" +
        "      \"sourceStartMs\": 0,\n" +
        "      \"sourceEndMs\": 0\n" +
        "    }\n" +
        "  ]\n" +
        "}\n\n" +
        "ПРАВИЛА:\n" +
        "1. Сохраняй ТОЛЬКО информацию, явно поддержанную транскриптом. Не додумывай факты, " +
        "имена, цифры, даты. Если информации недостаточно — не создавай memory.\n" +
        "2. Для каждого item ОБЯЗАТЕЛЬНО укажи source interval: sourceStartMs/sourceEndMs " +
        "в миллисекундах. В транскрипте реплики помечены [S1 00:12:03] (hh:mm:ss) — " +
        "интервал должен накрывать реплики, где этот факт прозвучал.\n" +
        "3. НЕ сохраняй мусор: приветствия, благодарности, «слышно?», «секунду», «я вернулся», " +
        "проверки связи, перебивания и прочий filler — они не полезны в будущем разговоре.\n" +
        "4. Полезные memories: decision, commitment, deadline, constraint, устойчивая " +
        "preference, project/person fact, responsibility, open question, risk, идея, " +
        "коррекция ранее сказанного.\n" +
        "5. importance — насколько факт важен в долгосрочной перспективе; " +
        "confidence — насколько транскрипт однозначно его подтверждает.\n" +
        "6. Каждый content — атомарное самодостаточное утверждение, понятное без контекста " +
        "встречи (вместо «он» — роль/имя, если известно).\n" +
        "7. Если извлекать нечего — верни пустой массив memories, summary всё равно заполни.";


    /// <summary>
    /// Клауза интенсивности извлечения (§6.4 аудита 2026-10-15). Дописывается
    /// в конец system/user-промпта извлечения; принимает "low"|"medium"|"high"
    /// (и русские синонимы), любое другое — "medium". Явная просьба «запомни»
    /// исполняется при любом уровне; запрет выдумывания — вне уровня.
    /// </summary>
    public static string IntensityClause(string? intensity)
    {
        var level = (intensity ?? "").Trim().ToLowerInvariant() switch
        {
            "low" or "низкая" => "low",
            "high" or "высокая" => "high",
            _ => "medium",
        };
        return level switch
        {
            "low" => "\nИНТЕНСИВНОСТЬ ИЗВЛЕЧЕНИЯ: НИЗКАЯ — извлекай только явно " +
                     "принятые решения, обязательства/договорённости с исполнителем или " +
                     "сроком, жёсткие требования и долгосрочные факты о людях и проектах. " +
                     "Всё сомнительное пропускай.\n",
            "high" => "\nИНТЕНСИВНОСТЬ ИЗВЛЕЧЕНИЯ: ВЫСОКАЯ — дополнительно извлекай " +
                      "важные детали: цифры, имена, адреса, связи между фактами и обоснования " +
                      "решений. Дублирующиеся факты объединяй в один. Высокая интенсивность " +
                      "НЕ разрешает догадываться или придумывать факты, не прозвучавшие " +
                      "в источнике.\n",
            _ => "\nИНТЕНСИВНОСТЬ ИЗВЛЕЧЕНИЯ: СРЕДНЯЯ — к решениям и обязательствам " +
                 "добавляй значимые детали (важные цифры, даты, имена, причины решений); " +
                 "мелкие проходные замечания пропускай.\n",
        };
    }

    /// <summary>
    /// Одна строка «ТЕКУЩАЯ НАСТРОЙКА» для контекста чата (§6 аудита 2026-10-16):
    /// действующий уровень интенсивности и его смысл — чтобы модель могла ответить
    /// на вопрос о настройке, а не гадать. Меняется при каждом запросе (уровень
    /// читается из конфига на момент запроса, не кэшируется).
    /// </summary>
    /// <param name="memoryEnabled">false → строка говорит, что извлечение не выполняется.</param>
    public static string IntensityStatusLine(string? intensity, bool memoryEnabled)
    {
        var (name, meaning) = (intensity ?? "").Trim().ToLowerInvariant() switch
        {
            "low" or "низкая" =>
                ("НИЗКАЯ", "сохраняются только решения, обязательства и долгосрочные факты"),
            "high" or "высокая" =>
                ("ВЫСОКАЯ", "сохраняется максимум деталей и связанных фактов без дублей"),
            _ =>
                ("СРЕДНЯЯ", "к решениям и обязательствам добавляются значимые детали"),
        };
        var off = memoryEnabled ? "" : " Память сейчас выключена — извлечение не выполняется.";
        return $"\n\nТЕКУЩАЯ НАСТРОЙКА: интенсивность извлечения фактов в память — {name} " +
               $"({meaning}); ни один уровень не разрешает выдумывать факты; явная просьба " +
               $"«запомни» исполняется при любом уровне.{off} При вопросе о настройке отвечай по этой строке.";
    }
    /// <summary>
    /// Честный статус recall для промпта: «найдено / найдено частично /
    /// ничего не найдено». Модель не должна выдавать слабые соседние факты за
    /// ответ и усечённый список — за полный. Score — ранкер recall (0..1);
    /// 0.60 — граница «сильное совпадение» (полное покрытие темы даёт ≥0.75,
    /// слабые лексические совпадения ~0.35-0.60 при блоках меньшего объёма).
    /// </summary>
    public static string RecallStatusLine(IReadOnlyList<BrainstormBuddy.Memory.MemoryRecallHit> hits,
        bool truncated)
    {
        if (hits.Count == 0)
            return "СТАТУС ПОИСКА ПАМЯТИ: ничего не найдено по этому запросу. " +
                   "Если и в прошлых встречах подтверждения нет — так и скажи («данных нет»), " +
                   "не выдумывай факты.";
        var weak = hits[0].Score < 0.60;
        var tail = truncated
            ? " Показана только часть (блок усечён по бюджету) — не выдавай фрагмент за полный список."
            : "";
        return weak
            ? $"СТАТУС ПОИСКА ПАМЯТИ: найдено частично — {hits.Count} слабых совпадений, " +
              "тема покрыта не полностью. Проверь, отвечают ли они на вопрос; если нет — " +
              "скажи прямо, что точных данных нет, и не подменяй ответ соседними фактами." + tail
            : $"СТАТУС ПОИСКА ПАМЯТИ: найдено {hits.Count} фактов." + tail;
    }

    /// <summary>
    /// Repair-промпт: модель вернула broken JSON — просим вернуть только валидный JSON
    /// по той же схеме (исходный текст ответа передаётся user-сообщением).
    /// Вызывающий код дописывает <see cref="IntensityClause"/> тем же уровнем, что
    /// был у основного запроса (§6.4).
    /// </summary>
    public const string Repair =
        "Ответ на прошлое сообщение должен был быть JSON по схеме extraction " +
        "(поля \"summary\" и \"memories\": type, content, importance, confidence, " +
        "speakerId, sourceStartMs, sourceEndMs), но он сломан. " +
        "Исправь его и верни ТОЛЬКО валидный JSON по той же схеме — без markdown, " +
        "без пояснений, без обрамления в ```. Не меняй смысл и не добавляй новых фактов.";
}
